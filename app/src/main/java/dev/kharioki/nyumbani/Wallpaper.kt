package dev.kharioki.nyumbani

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Matrix
import android.media.ExifInterface
import android.util.Log
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.asImageBitmap
import java.io.File
import java.io.IOException
import java.io.InputStream

/**
 * Wallpaper source, in order:
 *  1. Advanced: a file pushed over ADB to the app's own folder (no storage permission needed):
 *     /sdcard/Android/data/dev.kharioki.nyumbani/files/wallpaper.jpg  (or .png / .webp)
 *     It overrides whatever is picked in settings.
 *  2. The wallpaper picked in settings: one of [BUNDLED], or an image sent from a phone or copied
 *     from USB, stored as filesDir/wallpapers/custom-<timestamp>.jpg.
 *  3. The default bundled wallpaper.
 */
object Wallpaper {
    private const val TAG = "Nyumbani"
    private val CUSTOM_NAMES = listOf("wallpaper.jpg", "wallpaper.jpeg", "wallpaper.png", "wallpaper.webp")
    private const val CUSTOM_PREFIX = "custom-"

    /** Imported images are capped at 4K and re-encoded, which also strips EXIF (location etc.). */
    private const val MAX_W = 3840
    private const val MAX_H = 2160

    class Bundled(val id: String, val name: String, val asset: String)

    /** Generated by the scripts in /wallpaper; no photos, nothing copyrighted. */
    val BUNDLED = listOf(
        Bundled(LauncherConfig.DEFAULT_WALLPAPER_ID, "Savanna dusk", "wallpaper.jpg"),
        Bundled("night-ridge", "Night ridge", "wallpapers/night-ridge.jpg"),
        Bundled("dawn-mist", "Dawn mist", "wallpapers/dawn-mist.jpg"),
        Bundled("dusk-abstract", "Dusk abstract", "wallpapers/dusk-abstract.jpg"),
    )

    /** The ADB override file, if one has been pushed. */
    fun customFile(context: Context): File? {
        val dir = context.getExternalFilesDir(null) ?: return null
        return CUSTOM_NAMES.map { File(dir, it) }.firstOrNull { it.isFile && it.length() > 0 }
    }

    private fun importedDir(context: Context) = File(context.filesDir, "wallpapers")

    /** Images sent from a phone or copied from USB, newest first. Their file name is their id. */
    fun imported(context: Context): List<File> =
        importedDir(context).listFiles { f -> f.isFile && f.name.startsWith(CUSTOM_PREFIX) }
            ?.sortedByDescending { it.lastModified() }
            .orEmpty()

    fun isImported(id: String) = id.startsWith(CUSTOM_PREFIX)

    fun deleteImported(context: Context, id: String) {
        if (isImported(id)) File(importedDir(context), File(id).name).delete()
    }

    /** Where the wallpaper actually comes from right now, after overrides and fallbacks. */
    private class Source(val key: String, val label: String, val open: () -> InputStream)

    private fun bundledSource(context: Context, id: String): Source {
        val b = BUNDLED.firstOrNull { it.id == id } ?: BUNDLED.first()
        return Source("bundled:${b.id}", "assets/${b.asset}") { context.assets.open(b.asset) }
    }

    private fun fileSource(file: File) =
        Source("${file.name}:${file.length()}:${file.lastModified()}", file.path) { file.inputStream() }

    private fun resolve(context: Context, id: String): Source {
        customFile(context)?.let { return fileSource(it) }
        if (isImported(id)) {
            val file = File(importedDir(context), File(id).name)
            if (file.isFile) return fileSource(file)
        }
        return bundledSource(context, id)
    }

    /** Changes whenever the wallpaper on screen would change: a new pick, or the ADB file added or removed. */
    fun signature(context: Context, id: String): String = resolve(context, id).key

    /** The sharp wallpaper plus a heavily blurred copy used as the "glass" behind the widgets. */
    class Images(val sharp: ImageBitmap, val frosted: ImageBitmap)

    /**
     * Decodes at the smallest power-of-two downscale that still covers [targetW]x[targetH].
     * Android TV usually draws its interface at 1920x1080 even on a 4K panel, so a 4K image is
     * decoded at half size there: still pixel-sharp, and a quarter of the memory.
     * Call off the main thread.
     */
    fun load(context: Context, id: String, targetW: Int, targetH: Int): Images? {
        val source = resolve(context, id)
        // A broken file shouldn't leave you with a black screen: fall back to the default.
        val bitmap = decode(source, targetW, targetH)
            ?: decode(bundledSource(context, LauncherConfig.DEFAULT_WALLPAPER_ID), targetW, targetH)
            ?: return null
        return Images(sharp = bitmap.asImageBitmap(), frosted = frost(bitmap).asImageBitmap())
    }

    private fun decode(source: Source, targetW: Int, targetH: Int): Bitmap? = try {
        val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
        source.open().use { BitmapFactory.decodeStream(it, null, bounds) }
        if (bounds.outWidth <= 0 || bounds.outHeight <= 0) error("Unreadable image")

        var sample = 1
        while (bounds.outWidth / (sample * 2) >= targetW && bounds.outHeight / (sample * 2) >= targetH) sample *= 2

        val opts = BitmapFactory.Options().apply {
            inSampleSize = sample
            inPreferredConfig = Bitmap.Config.ARGB_8888
        }
        source.open().use { BitmapFactory.decodeStream(it, null, opts) }
    } catch (e: Exception) {
        Log.w(TAG, "Wallpaper failed to load from ${source.label}", e)
        null
    }

    /** A small preview (about [width] px wide) of a bundled wallpaper or an imported one. Call off the main thread. */
    fun thumbnail(context: Context, id: String, width: Int = 384): ImageBitmap? {
        val source = if (isImported(id)) fileSource(File(importedDir(context), File(id).name)) else bundledSource(context, id)
        return decode(source, width, width * 9 / 16)?.asImageBitmap()
    }

    /** A small preview of any image file, e.g. on a USB drive. Call off the main thread. */
    fun thumbnail(file: File, width: Int = 320): ImageBitmap? =
        decode(fileSource(file), width, width * 9 / 16)?.asImageBitmap()

    /**
     * Copies an image (from a phone upload or a USB drive) into the app as a new wallpaper:
     * upright per its EXIF orientation, at most 3840x2160, re-encoded as JPEG. Returns its id.
     * Throws if the file isn't a readable image. Call off the main thread.
     */
    fun import(context: Context, source: File): String {
        val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
        BitmapFactory.decodeFile(source.path, bounds)
        if (bounds.outWidth <= 0 || bounds.outHeight <= 0) throw IOException("That file isn't an image Nyumbani can read.")

        val rotation = runCatching {
            when (ExifInterface(source.path).getAttributeInt(ExifInterface.TAG_ORIENTATION, ExifInterface.ORIENTATION_NORMAL)) {
                ExifInterface.ORIENTATION_ROTATE_90 -> 90
                ExifInterface.ORIENTATION_ROTATE_180 -> 180
                ExifInterface.ORIENTATION_ROTATE_270 -> 270
                else -> 0
            }
        }.getOrDefault(0)
        val uprightW = if (rotation % 180 == 0) bounds.outWidth else bounds.outHeight
        val uprightH = if (rotation % 180 == 0) bounds.outHeight else bounds.outWidth
        val scale = minOf(1f, MAX_W.toFloat() / uprightW, MAX_H.toFloat() / uprightH)

        // Decode at a power-of-two size still at least as big as the result, then scale exactly.
        var sample = 1
        while (scale * sample * 2 <= 1f) sample *= 2
        val decoded = BitmapFactory.decodeFile(source.path, BitmapFactory.Options().apply {
            inSampleSize = sample
            inPreferredConfig = Bitmap.Config.ARGB_8888
        }) ?: throw IOException("That image couldn't be decoded.")

        val finalScale = scale * sample
        val matrix = Matrix().apply {
            postRotate(rotation.toFloat())
            postScale(finalScale, finalScale)
        }
        val upright = if (rotation == 0 && finalScale >= 0.999f) decoded
        else Bitmap.createBitmap(decoded, 0, 0, decoded.width, decoded.height, matrix, true)

        val dir = importedDir(context).apply { mkdirs() }
        val name = "$CUSTOM_PREFIX${System.currentTimeMillis()}.jpg"
        val partial = File(dir, "$name.part")
        try {
            partial.outputStream().buffered().use { out ->
                if (!upright.compress(Bitmap.CompressFormat.JPEG, 90, out)) throw IOException("Couldn't save the image.")
            }
            if (!partial.renameTo(File(dir, name))) throw IOException("Couldn't save the image.")
        } finally {
            partial.delete()
            if (upright !== decoded) upright.recycle()
            decoded.recycle()
        }
        return name
    }

    /**
     * Android 11 has no live blur, so we blur once per wallpaper: shrink to ~1/8 size, then run a
     * few box-blur passes (together roughly a Gaussian). Drawn back up with bilinear filtering it
     * reads as frosted glass, at a cost of a few milliseconds and ~150 KB.
     */
    private fun frost(source: Bitmap): Bitmap {
        val w = 240
        val h = (w * source.height / source.width).coerceAtLeast(1)
        val mid = Bitmap.createScaledBitmap(source, w * 3, h * 3, true)
        val small = Bitmap.createScaledBitmap(mid, w, h, true)
        if (mid !== source) mid.recycle()

        val px = IntArray(w * h)
        small.getPixels(px, 0, w, 0, 0, w, h)
        repeat(3) {
            boxBlur(px, w, h, radius = 4, horizontal = true)
            boxBlur(px, w, h, radius = 4, horizontal = false)
        }
        val out = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888)
        out.setPixels(px, 0, w, 0, 0, w, h)
        if (small !== source) small.recycle()
        return out
    }

    /** One running-sum box blur pass over opaque ARGB pixels, clamping at the edges. */
    private fun boxBlur(px: IntArray, w: Int, h: Int, radius: Int, horizontal: Boolean) {
        val lines = if (horizontal) h else w
        val len = if (horizontal) w else h
        val window = radius * 2 + 1
        val r = IntArray(len); val g = IntArray(len); val b = IntArray(len)
        fun index(line: Int, i: Int) = if (horizontal) line * w + i else i * w + line

        for (line in 0 until lines) {
            for (i in 0 until len) {
                val c = px[index(line, i)]
                r[i] = (c shr 16) and 0xFF; g[i] = (c shr 8) and 0xFF; b[i] = c and 0xFF
            }
            var sr = 0; var sg = 0; var sb = 0
            for (k in -radius..radius) {
                val j = k.coerceIn(0, len - 1)
                sr += r[j]; sg += g[j]; sb += b[j]
            }
            for (i in 0 until len) {
                px[index(line, i)] = (0xFF shl 24) or ((sr / window) shl 16) or ((sg / window) shl 8) or (sb / window)
                val add = (i + radius + 1).coerceAtMost(len - 1)
                val drop = (i - radius).coerceAtLeast(0)
                sr += r[add] - r[drop]; sg += g[add] - g[drop]; sb += b[add] - b[drop]
            }
        }
    }
}
